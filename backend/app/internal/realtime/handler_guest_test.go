func newWSServer(h *Handler) *httptest.Server {
	srv := httptest.NewServer(h)
	return srv
}

func newTestJWT(cfg config.Config) *security.JWTManager {
	return security.NewJWTManager(cfg.App.SecretKey, cfg.Auth.Issuer, cfg.Auth.AccessTokenExpiry, cfg.Auth.RefreshTokenExpiry)
}

func issueTestToken(t *testing.T, jwt *security.JWTManager, sessions repositories.SessionRepository, userID, sessID, tokID string) (string, string) {
	t.Helper()
	require.NoError(t, sessions.Set(context.Background(), &domain.Session{
		ID: sessID, UserID: userID, RefreshTokenID: tokID,
		ExpiresAt: time.Now().Add(time.Hour), CreatedAt: time.Now(),
	}))
	access, refresh, err := jwt.GenerateTokenPair(userID, sessID, tokID)
	require.NoError(t, err)
	return access, refresh
}

// fakeUserLookup satisfies realtime.UserLookup for WebSocket handler tests so
// player_joined/game_state carry usernames for registered users.
type fakeUserLookup struct {
	users map[string]*domain.User
}

func (f *fakeUserLookup) GetByID(_ context.Context, id string) (*domain.User, error) {
	if f.users == nil {
		return nil, nil
	}
	return f.users[id], nil
}

type guestWSTestEnv struct {
	*wsTestEnv
	roomSvc  services.RoomService
	users    *fakeUserLookup
	room     *domain.Room
	ownerID  string
	ownerAccess string
}

func newGuestWSTestEnv(t *testing.T) *guestWSTestEnv {
	t.Helper()
	cfg := config.Get()
	cfg.App.SecretKey = "ws-guest-secret"
	cfg.App.Domain = "http://example.com"
	cfg.Auth.Issuer = "drawo"
	cfg.Auth.AccessTokenExpiry = time.Hour
	cfg.Auth.RefreshTokenExpiry = 24 * time.Hour

	cacheClient, err := cache.NewClient(config.CacheConfig{Driver: "memory"})
	require.NoError(t, err)
	t.Cleanup(func() { _ = cacheClient.Close() })

	sessions := repositories.NewSessionRepo(cacheClient)
	roomRepo := repositories.NewRoomRepo(cacheClient)
	hub := NewHubWithDependencies(roomRepo, nil, nil)
	roomSvc := services.NewRoomService(roomRepo)
	users := &fakeUserLookup{users: map[string]*domain.User{
		"owner-1": {ID: "owner-1", Username: "TheOwner"},
		"user-2":  {ID: "user-2", Username: "Friend"},
	}}
	handler := NewHandler(cfg, hub, sessions, roomSvc, users)
	server := newWSServer(handler)
	t.Cleanup(server.Close)
	jwt := newTestJWT(cfg)

	ctx := context.Background()
	pw := "secret123"
	room, err := roomSvc.CreateRoom(ctx, "owner-1", domain.RoomTypePrivate, services.RoomSettings{
		Name: "Private", Password: &pw, Language: "en", MaxPlayers: 6, MaxRounds: 3,
		RoundTime: 40, WordSource: domain.WordSourceDefault,
	})
	require.NoError(t, err)
	// The invite code is generated by the service; store it for tests.
	require.NotEmpty(t, room.InviteCode)

	ownerAccess, _ := issueTestToken(t, jwt, sessions, "owner-1", "sess-owner", "tok-owner")

	return &guestWSTestEnv{
		wsTestEnv: &wsTestEnv{
			cfg:      cfg,
			sessions: sessions,
			roomRepo: roomRepo,
			hub:      hub,
			handler:  handler,
			server:   server,
			jwt:      jwt,
		},
		roomSvc:     roomSvc,
		users:       users,
		room:        room,
		ownerID:     "owner-1",
		ownerAccess: ownerAccess,
	}
}

func connectGuestWS(t *testing.T, e *guestWSTestEnv, guestToken string) *websocket.Conn {
	t.Helper()
	conn := e.dial(t)
	writeEnvelope(t, conn, EventAuth, AuthPayload{GuestToken: guestToken})
	writeEnvelope(t, conn, EventJoin, JoinPayload{Mode: "private", InviteCode: e.room.InviteCode})
	first := readEnvelopeWithDeadline(t, conn)
	assert.Equal(t, EventAuthOK, first.Type)
	joined := readUntilType(t, conn, EventJoined)
	var joinedPayload JoinedPayload
	require.NoError(t, json.Unmarshal(joined.Payload, &joinedPayload))
	assert.Equal(t, e.room.ID, joinedPayload.RoomID)
	return conn
}

func drainGameState(t *testing.T, conn *websocket.Conn) GameStatePayload {
	t.Helper()
	msg := readUntilType(t, conn, EventGameState)
	var gs GameStatePayload
	require.NoError(t, json.Unmarshal(msg.Payload, &gs))
	return gs
}

func TestWebSocketHandler_GuestJoinViaInviteAndPlayerList(t *testing.T) {
	env := newGuestWSTestEnv(t)
	ctx := context.Background()

	// Owner connects first.
	ownerConn := connectAuthenticated(t, env.wsTestEnv, env.ownerAccess, env.room.ID)
	gs := drainGameState(t, ownerConn)
	require.Len(t, gs.Players, 1)
	assert.Equal(t, "TheOwner", gs.Players[0].Username)
	assert.True(t, gs.Players[0].IsOwner)
	assert.False(t, gs.Players[0].IsGuest)

	// Guest joins via HTTP Join (password-checked), then opens WS with guest_token.
	joined, err := env.roomSvc.JoinRoom(ctx, env.room.InviteCode, "secret123")
	require.NoError(t, err)
	require.Equal(t, env.room.ID, joined.ID)
	guest, err := env.roomSvc.IssueGuestToken(ctx, env.room.ID, "   Alice   ")
	require.NoError(t, err)
	require.True(t, domain.IsGuestID(guest.GuestID))

	guestConn := connectGuestWS(t, env, guest.Token)
	guestGS := drainGameState(t, guestConn)
	require.Len(t, guestGS.Players, 2)
	var ownerP, guestP *PlayerState
	for i := range guestGS.Players {
		p := &guestGS.Players[i]
		if p.UserID == env.ownerID {
			ownerP = p
		}
		if p.UserID == guest.GuestID {
			guestP = p
		}
	}
	require.NotNil(t, ownerP)
	require.NotNil(t, guestP)
	assert.True(t, ownerP.IsOwner)
	assert.Equal(t, "TheOwner", ownerP.Username)
	assert.True(t, guestP.IsGuest)
	assert.False(t, guestP.IsOwner)
	assert.Equal(t, "Alice", guestP.Username)

	// Owner should have received player_joined broadcast for the guest.
	broadcast := readUntilType(t, ownerConn, EventPlayerJoined)
	var pb PlayerEventPayload
	require.NoError(t, json.Unmarshal(broadcast.Payload, &pb))
	assert.Equal(t, guest.GuestID, pb.UserID)
	assert.Equal(t, "Alice", pb.Username)

	// Clean closes.
	_ = ownerConn.Close()
	_ = guestConn.Close()
}

func TestWebSocketHandler_GuestRequiresBoundRoom(t *testing.T) {
	env := newGuestWSTestEnv(t)
	ctx := context.Background()

	// Mint a second room and a guest for it, then try to join env.room using that token.
	pw := "secret123"
	other, err := env.roomSvc.CreateRoom(ctx, "owner-1", domain.RoomTypePrivate, services.RoomSettings{
		Name: "Other", Password: &pw, Language: "en", MaxPlayers: 4, MaxRounds: 2,
		RoundTime: 30, WordSource: domain.WordSourceDefault,
	})
	require.NoError(t, err)
	_, err = env.roomSvc.JoinRoom(ctx, other.InviteCode, "secret123")
	require.NoError(t, err)
	g, err := env.roomSvc.IssueGuestToken(ctx, other.ID, "Wrong")
	require.NoError(t, err)

	conn := env.dial(t)
	writeEnvelope(t, conn, EventAuth, AuthPayload{GuestToken: g.Token})
	// Send a join that targets the OTHER room's id rather than the one bound to
	// the guest token — hub must reject.
	writeEnvelope(t, conn, EventJoin, JoinPayload{RoomID: other.ID, InviteCode: env.room.InviteCode})

	msg := readUntilType(t, conn, EventError)
	assert.Contains(t, string(msg.Payload), "guest token does not match")
	_ = conn.Close()
}

