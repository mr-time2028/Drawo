func TestWebSocketHandler_JoinValidation(t *testing.T) {
	e := newWSTestEnv(t)
	access, _ := e.createSession(t, "u1", "s1", "t1")
	conn := e.dial(t)
	writeEnvelope(t, conn, EventAuth, AuthPayload{AccessToken: access})
	// Empty/absent payload is fine — backend defaults to public matchmaking.
	writeEnvelope(t, conn, EventJoin, JoinPayload{})
	// But a mode that is not public/private/reconnect must fail.
	// Send it on a NEW connection because a bad join closes the socket.
	_ = conn.Close()

	conn2 := e.dial(t)
	writeEnvelope(t, conn2, EventAuth, AuthPayload{AccessToken: access})
	require.NoError(t, conn2.WriteJSON(MessageEnvelope{
		Type:    EventJoin,
		Payload: json.RawMessage(`{"mode":"bogus"}`),
	}))
	msg := readUntilType(t, conn2, EventError)
	assert.Contains(t, string(msg.Payload), "invalid join mode")
	_ = conn2.Close()

	// Missing invite_code for private mode.
	conn3 := e.dial(t)
	writeEnvelope(t, conn3, EventAuth, AuthPayload{AccessToken: access})
	writeEnvelope(t, conn3, EventJoin, JoinPayload{Mode: "private"})
	msg = readUntilType(t, conn3, EventError)
	assert.Contains(t, string(msg.Payload), "invite_code is required")
	_ = conn3.Close()
}

func TestWebSocketHandler_OwnerStartsGameOverWS(t *testing.T) {
	env := newGuestWSTestEnv(t)
	origCD := countdownDuration
	countdownDuration = 20 * time.Second
	t.Cleanup(func() { countdownDuration = origCD })

	access2, _ := env.createSession(t, "user-2", "sess-2", "tok-2")

	// Connect owner alone: no countdown (only one player).
	ownerConn := connectAuthenticated(t, env.wsTestEnv, env.ownerAccess, env.room.ID)
	_ = drainGameState(t, ownerConn)

	// Before friend joins, bump min-players so joining the second player does
	// NOT trigger the auto-countdown branch in handleJoin.
	r, err := env.hub.GetOrStartRoom(context.Background(), env.room.ID)
	require.NoError(t, err)
	r.state.MinPlayers = 99

	friendConn := connectAuthenticated(t, env.wsTestEnv, access2, env.room.ID)
	// Drain owner's player_joined broadcast and the post-join game_state on both
	// sockets before issuing any commands — otherwise those queued messages
	// surface in front of our start response.
	ownerJoined := readUntilType(t, ownerConn, EventPlayerJoined)
	var ownerPBP PlayerEventPayload
	require.NoError(t, json.Unmarshal(ownerJoined.Payload, &ownerPBP))
	assert.Equal(t, "user-2", ownerPBP.UserID)
	friendInit := drainGameState(t, friendConn)
	_ = drainGameState(t, ownerConn)
	require.Equal(t, GameStateWaitingForPlayers, friendInit.State, "auto-countdown must not fire during test")

	// Drop min back down so manual start succeeds (2 players present).
	r.state.MinPlayers = 2

	// Non-owner cannot start the game.
	writeEnvelope(t, friendConn, EventGame, GameEventPayload{Event: "start"})
	errMsg := readUntilType(t, friendConn, EventError)
	assert.Contains(t, string(errMsg.Payload), "only the room owner")

	// Owner starts the countdown over WS.
	writeEnvelope(t, ownerConn, EventGame, GameEventPayload{Event: "start"})

	gs := readUntilType(t, ownerConn, EventGameState)
	var ownerGS GameStatePayload
	require.NoError(t, json.Unmarshal(gs.Payload, &ownerGS))
	assert.Equal(t, GameStateCountdown, ownerGS.State)

	gs2 := readUntilType(t, friendConn, EventGameState)
	var friendGS GameStatePayload
	require.NoError(t, json.Unmarshal(gs2.Payload, &friendGS))
	assert.Equal(t, GameStateCountdown, friendGS.State)
	assert.Len(t, friendGS.Players, 2)

	// Starting again mid-countdown is rejected.
	writeEnvelope(t, ownerConn, EventGame, GameEventPayload{Event: "start"})
	errMsg = readUntilType(t, ownerConn, EventError)
	assert.Contains(t, string(errMsg.Payload), "already in progress")

	_ = ownerConn.Close()
	_ = friendConn.Close()
}

