import type { Player, Room } from '@/types';
import { avatarFor, mockMe } from './users';

function player(
  id: string,
  userId: string,
  username: string,
  score: number,
  isDrawer: boolean,
  isHost: boolean,
  isSelf: boolean,
): Player {
  return {
    id,
    userId,
    username,
    avatarUrl: avatarFor(username),
    score,
    isDrawer,
    isHost,
    isOnline: true,
    isSelf,
  };
}

